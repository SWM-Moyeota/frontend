package com.moyeota.presentation.core

import com.moyeota.domain.model.Ride

/**
 * **방 상세 폴링** 공통 규칙 — 25 배차 상태 · 26 운행 중이 주된 사용처이고,
 * 21 매칭 대기도 [PARTY_DETAIL_POLL_FLOOR_MS] 하한만 같이 쓴다.
 *
 * 세 화면의 처지가 다르다는 점을 먼저 구분해 둔다.
 * - **21 매칭 대기(동승·택시 공통)** 는 멤버 변화를 SSE 로 받으므로 **평상시 폴링이 0회**다.
 *   스트림이 끊겼을 때만 상세를 읽는 폴백이 돌고, 그때 쓰는 간격이 아래 하한이다.
 * - **25·26(택시 모드 전용)** 은 기다리는 전이에 SSE 도 FCM 도 없어 **상시 폴링을 없앨 수 없다**.
 *   아래 간격 표는 이 두 화면 이야기다.
 *
 * ## 왜 25·26 은 상세를 폴링하는가
 *
 * 두 화면이 기다리는 전이 `MATCHING → DRIVER_ASSIGNED → IN_RIDE → FINISHED` 에는
 * **SSE 이벤트도 FCM 도 없다.** 서버의 SSE 발행처는 참여·퇴장·종료뿐이고
 * (`PartyService`), 승객 푸시는 `DRIVER_ARRIVED` 하나뿐이다. 그래서 폴링을 없앨 수 없다.
 *
 * 예전에는 상태·인원·지문만 담은 가벼운 `GET /matching/rooms/{id}/status`(서버 쿼리 1개)를 읽고,
 * **지문이 달라진 주기에만** 방 상세를 읽었다. 그 엔드포인트와 지문이 백엔드에서 삭제됐다
 * (`04f6be7` — 매칭방 변화가 SSE 전용이 되면서 폴링용으로 만든 조회와 지문이 쓰이지 않게 됐다).
 * 지금 부르면 **404** 다. 그래서 수단을 [com.moyeota.domain.repository.RideRepository.getPartyDetail]
 * 로 바꿨다.
 *
 * ## 간격을 늘린 이유
 *
 * 상세는 **서버 쿼리 3개**(방 + 멤버 요약 + 탑승 횟수)에 경로 폴리라인까지 실어 오는 무거운 호출이다
 * (부하테스트에서 방 상세 폴링이 전체 요청의 45% — Backend #177). 옛 간격(25: 5초, 26: 4초)을
 * 그대로 두고 수단만 바꾸면 쿼리 부하가 3배가 된다:
 *
 * | 화면 | 옛 구조 | 간격을 그대로 두면 | 고른 간격 |
 * |---|---|---|---|
 * | 25 | 5초 × 쿼리 1개 = 0.20 q/s | 5초 × 3개 = 0.60 q/s | **7초** → 0.43 q/s |
 * | 26 | 4초 × 쿼리 1개 = 0.25 q/s | 4초 × 3개 = 0.75 q/s | **8초** → 0.38 q/s |
 *
 * 간격이 늘어난 대가는 **전이 감지 지연**(최악의 경우 간격만큼)이다. 두 화면이 서로 다른 값을
 * 쓰는 이유가 여기에 있다:
 * - **25 는 7초** — 이 간격이 기사 마커 갱신 주기도 함께 정한다(기사 위치 조회가 같은 루프에
 *   얹혀 있다). 40km/h 로 오는 택시가 한 걸음에 약 78m 를 뛰므로, 범위의 **짧은 쪽**을 쓴다.
 * - **26 은 8초** — 기다리는 전이가 운행 완료 하나뿐이고 지도에 움직일 마커가 없다
 *   (출발·도착·경로는 방 생성 시 확정된 값). 그래서 범위의 **긴 쪽**, 즉 가장 낮은 부하를 쓴다.
 *
 * [PARTY_DETAIL_POLL_FLOOR_MS] 밑으로는 내리지 않는다 — 그 아래부터는 위 표의 부하 증가가
 * 옛 구조를 넘어선다.
 *
 * ## 택시 모드 전용이다
 *
 * **동승 모드에서는 25·26 에 아예 들어갈 수 없다** — 서버가 `DISPATCHING`·`ONGOING` 을 내지 않으므로
 * 두 화면에 닿을 길이 없다(`docs/MODE-ROUTES.md`). 즉 이 폴링은 **택시 모드에서만 돈다.**
 * 실사용자 서버(동승)에서는 한 번도 돌지 않으므로, 위 부하는 택시 모드 사용자 수에만 비례한다.
 */
internal const val PARTY_DETAIL_POLL_FLOOR_MS = 6_000L

/**
 * 받아온 상세([fetched])를 화면 상태에 **반영해야 하는가** — 들고 있던 것([held])과 다를 때만 참.
 *
 * 폴링이 상세를 읽는 구조에서는 매 주기 같은 내용이 다시 온다. 그대로 흘려 넣으면 값이 똑같은데도
 * StateFlow 가 매번 새 값을 내보내 **불필요한 recomposition** 이 7~8초마다 돈다(25 는 지도·기사
 * 카드까지 다시 그린다).
 *
 * 판정이 `!=` 하나인 게 이 함수의 핵심이다. [Ride] 는 data class 이고 멤버 목록도 data class [
 * com.moyeota.domain.model.User] 의 리스트라 **전 필드 깊은 비교**가 된다. 예전에 지문(서버
 * fingerprint)이 필요했던 이유는 폴링이 받는 게 **요약**(상태·인원수)이라 「인원수는 같은데 멤버가
 * 교체된」 변화를 못 잡았기 때문인데, 받는 게 곧 상세가 된 지금은 그 경우까지 `==` 가 그냥 잡는다.
 * 지문 비교 최적화(「안 바뀌었으면 상세 재조회 생략」)는 **원리적으로 불가능해졌다** — 바뀌었는지
 * 알려면 상세를 받아야 하고, 받은 뒤에는 생략할 조회가 없다. 남은 최적화는 이 **화면 갱신 생략**뿐이다.
 *
 * [held] 가 null 인 경우(첫 조회 실패로 화면이 에러였던 때)는 항상 참이다 — 그 자리에서 복구된다.
 */
internal fun shouldPublishDetail(held: Ride?, fetched: Ride): Boolean = held != fetched
