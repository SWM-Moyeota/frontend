package com.moyeota.presentation.core

/**
 * 35 마이페이지가 여는 운영 주소 — 이용약관 · 개인정보 처리방침 · 문의 메일.
 *
 * **세 값 모두 지금은 null 이다.** 운영 도메인과 문의 메일 계정이 아직 정해지지 않았다.
 * 주소가 확정되면 **이 파일 한 곳만 채운다** — 화면은 값의 내용이 아니라 유무만 본다.
 *
 * null 인 값은 해당 메뉴 행을 **아예 그리지 않는다**. 「준비 중」 같은 자리표시를 두지 않는 이유:
 * 눌러도 아무 일이 없는 행은 사용자에게 고장으로 읽히고, 스토어 심사에서도 죽은 링크로 잡힌다.
 * 행이 없으면 없는 기능을 기다리지 않는다 (`docs/BACKEND-GAP-CLEANUP.md` 의 원칙과 같다).
 *
 * 주소를 채울 때 주의:
 * - [PRIVACY_URL] 은 Play 콘솔 「개인정보처리방침」에 등록하는 주소와 **같은 페이지**여야 한다.
 * - 셋 다 앱 밖(브라우저 · 메일 앱)에서 열린다 — 로그인 없이 접근 가능한 공개 주소를 쓴다.
 */
object SupportLinks {

    /** 이용약관 페이지 주소(`https://…`). 정해지기 전에는 null — 행을 숨긴다. */
    val TERMS_URL: String? = null

    /** 개인정보 처리방침 페이지 주소(`https://…`). Play 콘솔 등록 주소와 같아야 한다. */
    val PRIVACY_URL: String? = null

    /** 문의를 받을 메일 주소. 메일 앱으로 제목·환경 정보까지 채워 띄운다. */
    val CONTACT_EMAIL: String? = null
}
