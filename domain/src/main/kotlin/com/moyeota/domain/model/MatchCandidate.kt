package com.moyeota.domain.model

/**
 * 「걸어서 가까운 방」 추천 하나(`POST /matching/rooms/realtime`).
 *
 * 지도 뷰포트로 훑는 17 탐색과 **목적이 다르다.** 저쪽은 "이 화면에 보이는 방 전부"고, 이쪽은
 * "내 출발지·도착지 양쪽에서 걸어갈 만한 방 몇 개"다. 서버가 양쪽 300m 안(AND)에서 고른 뒤
 * OSRM 도보 시간 합으로 정렬해 **0~5개**를 준다.
 *
 * **빈 목록은 정상이다.** 출발지 *그리고* 도착지가 각각 300m 안이어야 해서 초기에는 그게 기본
 * 상태다. 화면은 이걸 실패로 보이게 하면 안 된다 — 「지금은 맞는 방이 없어요 → 방 만들기」로
 * 흘려야 한다.
 *
 * **받은 순서가 계약이다.** 서버가 이미 도보 시간 순으로 정렬했으므로 앱에서 다시 정렬하지 않는다.
 */
data class MatchCandidate(
    /**
     * 방의 뼈대만 채운 [Ride] — id·출발·도착·좌표·정원뿐이다.
     *
     * **[Ride.members] 는 비어 있고 요금도 0 이다.** 서버 응답(`NearbyPartySummary`)에
     * `currentMembers`·요금·경로가 없기 때문이지, 그런 방이라서가 아니다. 그래서 이 값으로
     * 「2/3명」이나 「1인당 얼마」를 그리면 안 된다 — 합류 화면(19)이 방 상세를 읽어 채운다.
     */
    val ride: Ride,
    /**
     * 탑승지까지 걷는 시간 **+** 하차지에서 목적지까지 걷는 시간(초).
     *
     * 이름에 walk 를 박은 이유: 서버 필드명은 `totalSeconds` 인데, 그대로 쓰면 「총 소요시간」으로
     * 읽혀 **차 타는 시간이 포함된 것처럼** 오해된다. 화면에도 「걸어서 N분」으로 써야 한다.
     * 두 구간을 나눠 보여줄 수는 없다 — 서버가 합만 준다.
     */
    val walkSeconds: Int,
)
